-- Вечерние уведомления: время по умолчанию 23:00 -> 22:00.
-- Значение по умолчанию для НОВЫХ пользователей теперь задаётся в коде (src/db.ts → DEFAULT_NOTIFY_TIME),
-- а этот запрос переводит уже существующих пользователей, у которых стояло старое 23:00.
UPDATE users SET notify_time = '22:00' WHERE notify_time = '23:00';
